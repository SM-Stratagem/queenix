#!/bin/sh
# Run the PRODUCTION images locally (docker-compose.prod.yml) before deploying.
#   ./scripts/prod-local.sh          start / rebuild
#   ./scripts/prod-local.sh --demo   also seed demo accounts + dataset
#   docker compose -f docker-compose.prod.yml --env-file .env.prod.local down   stop
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
ENV_FILE=.env.prod.local
COMPOSE="docker compose -f docker-compose.prod.yml --env-file $ENV_FILE"

docker info >/dev/null 2>&1 || { echo "✗ Docker is not running — open Docker Desktop first."; exit 1; }

# LAN IP: Convex (in Docker) must reach the web app's OIDC issuer URL, and
# phones must reach both — container-localhost works for neither.
LAN_IP="$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || true)"
[ -n "$LAN_IP" ] || LAN_IP=localhost

# Secrets: generated once, kept across restarts (the Convex admin key and
# every session depend on them). Never commit this file.
if [ ! -f "$ENV_FILE" ]; then
  echo "Generating $ENV_FILE (secrets) ..."
  {
    echo "# Generated by scripts/prod-local.sh — local prod testing only. Never commit."
    node scripts/gen-secrets.mjs
    echo "POSTGRES_PASSWORD=$(node -e "console.log(require('crypto').randomBytes(24).toString('hex'))")"
    echo "CONVEX_INSTANCE_SECRET=$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")"
  } > "$ENV_FILE"
fi
# URLs follow the current network (refreshed every run).
sed -i.bak '/^AUTH_BASE_URL=/d;/^PUBLIC_CONVEX_URL=/d;/^PUBLIC_CONVEX_SITE_URL=/d;/^CONVEX_DEPLOY_KEY=/d' "$ENV_FILE" && rm -f "$ENV_FILE.bak"
{
  echo "AUTH_BASE_URL=http://$LAN_IP:4000"
  echo "PUBLIC_CONVEX_URL=http://$LAN_IP:4210"
  echo "PUBLIC_CONVEX_SITE_URL=http://$LAN_IP:4211"
} >> "$ENV_FILE"

$COMPOSE up -d --wait postgres convex-backend
# Admin key is derived from INSTANCE_NAME + INSTANCE_SECRET (stable per secret).
ADMIN_KEY="$($COMPOSE exec -T convex-backend ./generate_admin_key.sh | tail -1)"
echo "CONVEX_DEPLOY_KEY=$ADMIN_KEY" >> "$ENV_FILE"

if [ "${1:-}" = "--demo" ]; then
  $COMPOSE --profile demo up -d --build --wait web
  $COMPOSE --profile demo up seed
else
  $COMPOSE up -d --build --wait web
fi

cat <<INFO

================ QUEENIX (PRODUCTION BUILD, LOCAL) ================
Web         : http://$LAN_IP:4000/login
Convex API  : http://$LAN_IP:4210
Inbox       : http://localhost:8026   (stand-in for your email/SMS providers)
Health      : curl http://localhost:4000/api/health
Mobile      : point the app at this stack:
  cd apps/mobile && EXPO_PUBLIC_AUTH_BASE_URL=http://$LAN_IP:4000 \\
    EXPO_PUBLIC_CONVEX_URL=http://$LAN_IP:4210 npx expo start --lan
Stop        : $COMPOSE down
===================================================================
INFO
